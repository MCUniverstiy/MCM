  function rememberOriginals() {
    document.querySelectorAll('[data-i18n]').forEach(function (element) {
      if (!element.hasAttribute('data-i18n-original')) {
        element.setAttribute('data-i18n-original', element.innerHTML);
      }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (element) {
      if (!element.hasAttribute('data-i18n-placeholder-original')) {
        element.setAttribute('data-i18n-placeholder-original', element.getAttribute('placeholder') || '');
      }
    });
  }

  function applyLang(lang) {
    rememberOriginals();
    var useChinese = lang === 'zh';

    document.querySelectorAll('[data-i18n]').forEach(function (element) {
      var key = element.getAttribute('data-i18n');
      var translated = zh[key];
      element.innerHTML = useChinese && translated !== undefined
        ? translated
        : element.getAttribute('data-i18n-original');
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(function (element) {
      var key = element.getAttribute('data-i18n-placeholder');
      var translated = zh[key];
      element.setAttribute('placeholder', useChinese && translated !== undefined
        ? translated
        : element.getAttribute('data-i18n-placeholder-original'));
    });

    document.querySelectorAll('.lang-option').forEach(function (button) {
      var isEnglish = button.textContent.trim() === 'EN';
      var active = useChinese ? !isEnglish : isEnglish;
      button.classList.toggle('is-active', active);
      button.setAttribute('aria-pressed', active ? 'true' : 'false');
    });

    document.documentElement.lang = useChinese ? 'zh-Hant' : 'en';
    try { localStorage.setItem('mcm-lang', useChinese ? 'zh' : 'en'); } catch (error) {}
  }

  window.switchLang = applyLang;

  function init() {
    var saved = 'en';
    try { saved = localStorage.getItem('mcm-lang') || 'en'; } catch (error) {}
    applyLang(saved === 'zh' ? 'zh' : 'en');
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
